import test from 'node:test';
import assert from 'node:assert/strict';
import {randomBytes} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import pg from 'pg';
import {parseModel} from '../dist/schema.js';
import {PostgresStore} from '../dist/store.js';
import {createChefServer} from '../dist/graphql.js';
import config from '../../../examples/transaction-breakdown/chef.config.ts';

const url=process.env.CHEF_TEST_DATABASE_URL;
test('PostgreSQL: previous-output enrichment, nested GraphQL, restart and reorg restore one canonical model',{skip:!url},async t=>{
 const project=`t_${randomBytes(12).toString('hex')}`;
 const model=parseModel(await readFile(new URL('../../../examples/transaction-breakdown/schema.graphql',import.meta.url),'utf8'));
 const opts={project,fingerprint:'breakdown-test-v1',startHeight:0,network:'regtest',reorgWindow:4,model};
 let store=new PostgresStore(url,opts);await store.migrate();await store.acquire();
 let server;
 t.after(async()=>{if(server){server.closeAllConnections();await new Promise(r=>server.close(r));}await store.close();const c=new pg.Client({connectionString:url});await c.connect();try{assert.match(project,/^t_[0-9a-f]{24}$/);await c.query(`DROP SCHEMA "chef_${project}" CASCADE`);}finally{await c.end();}});
 const h=n=>n.toString(16).padStart(64,'0');
 const block=(height,n,previous)=>({height,hash:h(n),previousHash:h(previous),time:height});
 const funding=(id,value)=>({txid:h(id),index:0,blockHeight:0,version:4,locktime:0,decoded:{vin:[{coinbase:'00'}],vout:[{n:'0',value,scriptPubKey:{addresses:['tFunding']}}]}});
 const spend=(id,previous)=>({txid:h(id),index:0,blockHeight:1,version:4,locktime:0,decoded:{vin:[{txid:h(previous),vout:'0'}],vout:[{n:'0',value:'0.0009',scriptPubKey:{address:'tDestination'}}]}});
 const apply=async(branch,transactions)=>store.applyBatch(branch,async(b,entities)=>config.indexer.transaction({block:b,transaction:transactions[b.height],context:{entities}}));
 await apply([block(0,10,0),block(1,11,10)],[funding(1,'0.001'),spend(2,1)]);
 await store.close();store=new PostgresStore(url,opts);await store.acquire();
 server=createChefServer({store,model,token:'breakdown-integration-token'});await new Promise(r=>server.listen(0,'127.0.0.1',r));
 const query=async(q)=>{const r=await fetch(`http://127.0.0.1:${server.address().port}/graphql`,{method:'POST',headers:{'Content-Type':'application/json',authorization:'Bearer breakdown-integration-token'},body:JSON.stringify({query:q})});return {status:r.status,body:await r.json()};};
 const q=id=>`{ TransactionById(id:"${h(id)}") { inputs { resolution valueZat addresses previousOutput { valueZat addresses transaction { id } } } outputs { valueZat addresses } } }`;
 const a=await query(q(2));assert.equal(a.status,200);
 assert.deepEqual(a.body.data.TransactionById.inputs,[{resolution:'resolved',valueZat:'100000',addresses:['tFunding'],previousOutput:{valueZat:'100000',addresses:['tFunding'],transaction:{id:h(1)}}}]);
 const page=await query('{ TransactionOutputList(first:1) { items { id } nextCursor } }');const cursor=page.body.data.TransactionOutputList.nextCursor;assert.ok(cursor);
 await store.markReconciling();assert.equal((await query(q(2))).status,503);
 await store.rollback(-1,h(0));await store.markReady();
 assert.equal((await query(q(2))).body.data.TransactionById,null);
 assert.equal((await query(`{ TransactionOutputList(first:1,after:"${cursor}") { items { id } } }`)).status,409);
 await apply([block(0,20,0),block(1,21,20)],[funding(3,'0.002'),spend(4,3)]);
 const replacement=await query(q(4));assert.equal(replacement.status,200);assert.equal(replacement.body.data.TransactionById.inputs[0].valueZat,'200000');
 assert.equal((await query(q(2))).body.data.TransactionById,null);
 const oldOutput=await store.read(v=>v.get('TransactionOutput',`${h(1)}:0`));assert.equal(oldOutput,null);
});
