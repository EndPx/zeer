import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

const a = JSON.parse(await readFile(new URL('../static/operations/2026-10-28-prep-archive-budget-recovery.json', import.meta.url), 'utf8'));
const {before, proof, gc, retained, acceptance: end, closing} = a;
assert.equal(a.kind, 'operational-recovery');
assert.equal(before.budgetBytes, 24 * 1024 ** 3);
assert.equal(before.appendReserveBytes, 256 * 1024 ** 2);
assert.equal(Object.values(before.storageBytes).reduce((sum, n) => sum + n, 0), before.archiveBytes);
assert.equal(before.budgetBytes - before.archiveBytes - before.appendReserveBytes, before.freeAboveAppendReserveBytes);
assert(before.freeAboveAppendReserveBytes < 0);
assert(before.freePhysicalBytes > 25 * 1024 ** 3);
assert.equal(proof.catalog_file_sha256, before.catalog.fileSha256);
assert.equal(gc.catalogFileSha256Unchanged, before.catalog.fileSha256);
assert.equal(proof.candidates, gc.reclaimedDirectories + retained.additionalDirectories);
assert.equal(proof.eligible_bytes, gc.reclaimedBytes);
assert.equal(before.storageBytes.candidate_retired, gc.reclaimedBytes + retained.additionalBytes);
assert.equal(gc.archiveBytesBefore, before.archiveBytes);
assert.equal(gc.archiveBytesBefore - gc.reclaimedBytes, gc.archiveBytesAfter);
assert.equal(retained.originalProtectedDirectories, 79);
assert.equal(Object.values(retained.originalClassifications).reduce((sum, n) => sum + n, 0), 79);
assert.equal(retained.additionalClassifications.noncanonical_branch, retained.additionalDirectories);
assert(retained.originalManifestsUnchanged && retained.additionalFilesUnchanged);
assert.equal(retained.incompleteOrTemporaryDirectories, 0);
const change = a.approvedBudgetChange;
assert(change.approvedByUser);
assert.equal(change.archiveBudgetBytesBefore, before.budgetBytes);
assert.equal(change.archiveBudgetBytesAfter, 26 * 1024 ** 3);
assert.equal(change.aggregateBudgetGiBBefore, 60);
assert.equal(change.aggregateBudgetGiBAfter, 64);
assert.equal(change.aggregateStopGiBAfter, 63);
assert.equal(change.minimumHostFreeGiBUnchanged, 25);
assert.equal(change.nodeBudgetGiBUnchanged, 35);
assert.equal(change.appendReserveBytesUnchanged, before.appendReserveBytes);
assert(change.projectedAggregateAtFullPrepPlus512MiB < 62 * 1024 ** 3);
assert.equal(end.budgetBytes, change.archiveBudgetBytesAfter);
assert.equal(end.reserveBytes, before.appendReserveBytes);
assert.equal(end.budgetBytes - end.archiveBytes - end.reserveBytes, end.freeAboveAppendReserveBytes);
assert(end.freeAboveAppendReserveBytes > 0);
assert(end.prep.ready && end.prep.indexed_height > before.catalog.head);
const observed = Object.entries(end.observedNewHeights);
assert(observed.length >= 3);
for (const [height, item] of observed) {
  assert(Number(height) > change.catalogBefore.head);
  assert.equal(item.sourceHash, item.archiveHash);
}
assert.equal(end.consumerCheckpoint.status, 'ready');
assert.equal(end.consumerSource.status, 'available');
assert(end.consumerProjectGenerationAnchorAndContainersUnchanged && end.previousHeadHashUnchanged);
assert.equal(end.graphQL.status, 'ready');
assert(end.queryResults.length >= 6);
assert.equal(new Set(end.queryResults.filter(q => q.http === 200).map(q => q.case)).size, 3);
assert.equal(a.productionWriter.changed, false);
assert.equal(a.productionReader.changed, false);
assert.equal(end.actualExecutables['zeer-testnet-prep-follow.service'].sha256, a.productionWriter.sha256);
assert.equal(end.actualExecutables['zeer-testnet-prep-optimized-native.service'].sha256, a.productionReader.sha256);
assert.equal(closing.status, 'PASS');
assert(closing.prep.ready && closing.sourceGapBlocks <= 2);
assert(closing.consumerHeight > before.catalog.head);
assert.equal(closing.consumerCaughtUp, closing.consumerGapBlocks <= 2);
assert(closing.sourceAgeSeconds >= 0 && closing.sourceAgeSeconds < 30);
assert.equal(closing.guard.status, 'PASS');
assert.equal(closing.guard.limits.aggregate_budget_gib, 64);
assert.equal(closing.guard.limits.minimum_host_free_gib, 25);
assert.equal(closing.writerRuntimeMaxDiskGiB, 26);
assert.equal(closing.readerPidUnchangedDuringBudgetRestart, change.readerPidUnchanged);
assert(closing.operatorUnitsInactive && closing.publicDemoUnitsRestored);
for (const unit of Object.values(closing.resources)) {
  assert.equal(unit.cpuQuota, '500ms');
  assert.equal(Number(unit.memoryEvents.oom), 0);
  assert.equal(Number(unit.memoryEvents.oom_kill), 0);
}
console.log(`PASS: ${gc.reclaimedDirectories} proven copies / ${gc.reclaimedBytes} bytes reclaimed; catalog unchanged by GC; ${retained.originalProtectedDirectories + retained.additionalDirectories} retained directories; source and consumer ready; approved 26/64 GiB allocation.`);
